// Generates src/scripts/land-points.ts: a compact list of dots on land for the 3D globe.
// Run once with `npm run globe:points` (only needed if you change density).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topo, topo.objects.land);

// Fibonacci sphere sampling gives an even dot grid with no pole clustering.
const N = 16000;
const out = [];
const golden = Math.PI * (3 - Math.sqrt(5));
for (let i = 0; i < N; i++) {
  const y = 1 - (i / (N - 1)) * 2;
  const r = Math.sqrt(1 - y * y);
  const theta = golden * i;
  const lat = (Math.asin(y) * 180) / Math.PI;
  let lon = ((theta * 180) / Math.PI) % 360;
  if (lon > 180) lon -= 360;
  if (lat < -60) continue; // skip Antarctica for a cleaner look
  if (geoContains(land, [lon, lat])) out.push(Math.round(lat * 10), Math.round(lon * 10));
}
const body = `// Generated by scripts/build-land-points.mjs. Pairs of [lat*10, lon*10].\nexport const LAND = new Int16Array([${out.join(',')}]);\n`;
writeFileSync('src/scripts/land-points.ts', body);
console.log(`${out.length / 2} land points, ${(body.length / 1024).toFixed(1)} KB`);
